#!/usr/bin/env python3
"""Turns feature-test results into parity/feature-check.md and the generated part of each pending.md.

  python3 parity/tests/report.py [--windows-pending PATH]

Reads parity/features.md and parity/results/<platform>.json (mac, linux, windows; any that exist). In each
pending.md only the block between the feature-tests markers is rewritten; the rest stays as written by hand.
"""
import argparse, json, os, re, collections

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SECTION = {"W": "§2", "T": "§2", "P": "§2", "B": "§2", "M": "§2", "R": "§3", "S": "§4", "E": "§5", "X": "§5",
           "D": "§5", "G": "§5", "A": "§5", "L": "§6", "U": "§7", "C": "§8", "Y": "§9", "Z": "§10"}
PLATFORMS = [("mac", "Mac"), ("linux", "Linux"), ("windows", "Windows")]
START, END = "<!-- feature-tests:start -->", "<!-- feature-tests:end -->"


def features():
    groups, names = [], {}
    for line in open(os.path.join(REPO, "parity", "features.md"), encoding="utf-8"):
        m = re.match(r"## ([A-Z]): (.+)", line)
        if m:
            groups.append((m.group(1), m.group(2), []))
            continue
        m = re.match(r"- \*\*([A-Z]\d+)\*\* (.+)", line)
        if m:
            names[m.group(1)] = m.group(2).strip()
            groups[-1][2].append(m.group(1))
    return groups, names


def load(platform):
    path = os.path.join(REPO, "parity", "results", f"{platform}.json")
    if not os.path.exists(path):
        return None
    data = json.load(open(path, encoding="utf-8-sig"))
    by_id = collections.defaultdict(list)
    for r in data["results"]:
        by_id[r["id"]].append(r)
    return data["run"], by_id


def rollup(results):
    """One status per feature from its tests: the worst outcome wins."""
    if not results:
        return "untested", "no test yet"
    statuses = [r["status"] for r in results]
    for status in ("broken", "missing", "error"):
        hits = [r for r in results if r["status"] == status]
        if hits:
            return status, "; ".join(f"{h['test']}: {h['detail']}" for h in hits)
    if all(s == "n/a" for s in statuses):
        return "n/a", results[0]["detail"]
    if "unverified" in statuses:
        reasons = "; ".join(sorted({r["detail"] for r in results if r["status"] == "unverified"}))
        return ("partly checked" if "works" in statuses else "unverified"), reasons
    return "works", ""


LABEL = {"works": "Works", "partly checked": "Works (partly checked)", "broken": "**Broken**", "missing": "Missing",
         "error": "Test error", "unverified": "Not checked", "n/a": "N/A", "untested": "No test"}


def short(text, limit=160):
    text = text.replace("|", "/").replace("\n", " ")
    return text if len(text) <= limit else text[:limit - 1].rsplit(" ", 1)[0] + "…"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--windows-pending", default=os.path.join(REPO, "windows", "pending.md"))
    args = parser.parse_args()
    groups, names = features()
    loaded = {p: load(p) for p, _ in PLATFORMS}
    status = {p: {fid: rollup(loaded[p][1].get(fid, [])) for fid in names} for p, _ in PLATFORMS if loaded[p]}

    out = ["# Feature check: every version against the Mac's feature list", "",
           f"Generated by `parity/tests/report.py` from `parity/features.md` ({len(names)} features) and the feature tests in "
           "`parity/tests` (one fresh private copy of the app per test, driven through its test bridge; see SPECIFICATION.md §9).", ""]
    for p, title in PLATFORMS:
        if loaded[p]:
            out.append(f"- {title}: run {loaded[p][0]}.")
    out += ["", "**Statuses:** Works (every check passed) · Works (partly checked: some checks passed, the rest need a person) · "
            "**Broken** (an expectation failed) · Missing (no such command, or greyed out) · Not checked (needs a person, an "
            "SSH host, sudo or a larger bridge; the reason is given) · N/A (not needed on that platform).", "", "## Summary", ""]
    order = ["works", "partly checked", "broken", "missing", "unverified", "error", "n/a"]
    out.append("| | " + " | ".join(LABEL[o].strip("*") for o in order) + " |")
    out.append("|---|" + "---|" * len(order))
    for p, title in PLATFORMS:
        if p in status:
            counts = collections.Counter(s for s, _ in status[p].values())
            out.append(f"| {title} | " + " | ".join(str(counts.get(o, 0)) for o in order) + " |")
    out.append("")
    for g, gname, ids in groups:
        out += [f"## {g}: {gname}", "", "| Id | Feature | " + " | ".join(t for p, t in PLATFORMS if p in status) + " |",
                "|---|---|" + "---|" * len(status)]
        for fid in ids:
            cells = []
            for p, _ in PLATFORMS:
                if p in status:
                    s, detail = status[p][fid]
                    cells.append(LABEL[s] + (f": {short(detail, 110)}" if s in ("broken", "missing", "error") and detail else ""))
            out.append(f"| {fid} | {short(names[fid], 90)} | " + " | ".join(cells) + " |")
        out.append("")
    open(os.path.join(REPO, "parity", "feature-check.md"), "w", encoding="utf-8").write("\n".join(out))

    targets = {"mac": os.path.join(REPO, "pending.md"), "linux": os.path.join(REPO, "linux", "pending.md"),
               "windows": args.windows_pending}
    for p, title in PLATFORMS:
        if p not in status or not targets[p]:
            continue
        block = generated(p, title, status[p], names, loaded[p][0])
        path = targets[p]
        text = open(path, encoding="utf-8").read() if os.path.exists(path) else default_header(title)
        if START in text:
            text = text[:text.index(START)] + block + text[text.index(END) + len(END):]
        else:
            text = text.rstrip() + "\n\n" + block + "\n"
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w", encoding="utf-8").write(text)
    print("wrote parity/feature-check.md and", ", ".join(os.path.relpath(targets[p], REPO) for p in status if targets[p]))


def default_header(title):
    return (f"# {title}: what isn't production-ready yet\n\n"
            f"What the {title} version still needs before it can ship with as few bugs as possible: everything a feature test "
            "found broken or missing, and every feature no automatic test covers yet. Fix broken items first, one pull "
            "request each, and tick an item with its PR number once it is fixed and its test passes. `bugs.md` and "
            "`enhancements.md` stay the record of requests and releases.\n")


def generated(platform, title, status, names, run):
    lines = [START, f"## Feature test results ({run})", "",
             "Written by `parity/tests/report.py`; rerun the tests and the report rather than editing this part.", ""]
    def section(heading, kinds, note):
        rows = [(fid, s, d) for fid, (s, d) in status.items() if s in kinds]
        if not rows:
            return
        lines.extend([f"### {heading} ({len(rows)})", "", note, ""])
        for fid, s, d in rows:
            lines.append(f"- [ ] **{fid}** {short(names[fid], 100)} ({SECTION[fid[0]]})" + (f": {short(d, 220)}" if d else ""))
        lines.append("")
    section("Broken", ("broken", "error"), "A test ran and the feature didn't do what the Mac version does.")
    section("Missing", ("missing",), "The command isn't there, or it's greyed out.")
    section("Not checked automatically", ("unverified", "partly checked", "untested"),
            "Try these by hand before a release, or extend the test bridge so a test can check them.")
    lines.append(END)
    return "\n".join(lines)


if __name__ == "__main__":
    main()
